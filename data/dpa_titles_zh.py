def apply_all():
    changed = 0
    with connect() as db:
        for prefix, title in TITLES.items():
            rows = db.execute("SELECT id FROM media_index WHERE id LIKE ? AND date_kind='event'",
                              (prefix + "%",)).fetchall()
            if len(rows) != 1:
                raise ValueError(f"{prefix}: expected one event, got {len(rows)}")
            changed += db.execute("UPDATE media_index SET title_zh=? WHERE id=?",
                                  (title, rows[0]["id"])).rowcount
    print(f"已写入 {changed} 条中文标题")


if __name__ == "__main__":
    apply_all()
